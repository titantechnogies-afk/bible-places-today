"""Builds supabase/activate-all.sql from the separate scripts. Run: python3 tools/build-activate-sql.py"""
import os
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
parts = [('setup', 'PROFILES, GROUPS, PHONE NOTIFICATIONS'), ('community', 'PROFILE PICTURES, FRIENDS, TESTIMONIES, CHURCHES, PRAYER PARTNERS'),
         ('sharing', 'MEMBERS LIST AND SHARING NOTES WITH FRIENDS'), ('stats', 'MEMBER COUNT ON THE HOME SCREEN'), ('help', 'HELP & PRAYER MESSAGES')]
out = ["""-- =====================================================================================
-- JUST ONE MORE LORD — ACTIVATE EVERYTHING IN ONE GO   (generated by tools/build-activate-sql.py)
-- Switches on: profile pictures, friends, the members list, sharing notes & highlights with friends,
-- testimonies, church finder, prayer partners, the member count, and the private
-- "Need help or prayer?" messages with your admin inbox.
--
-- HOW TO RUN IT:
--   1. Sign up in the app with your own email first (My profile).
--   2. Scroll to the VERY BOTTOM of this file and change YOUR-EMAIL-HERE to that email.
--   3. Supabase → your project → SQL Editor → New query → paste ALL of this → Run.
-- Safe to run again at any time: it never deletes your users, messages or data.
-- ====================================================================================="""]
for f, title in parts:
    s = open(os.path.join(R, 'supabase', f + '.sql'), encoding='utf-8').read()
    if f == 'help': s = '\n'.join(l for l in s.splitlines() if not l.startswith('insert into public.app_admins') and not l.startswith('-- 3) MAKE YOURSELF'))
    out.append(f"\n-- ===================== {title} ({f}.sql) =====================\n{s.strip()}\n")
out.append("""
-- ===================== MAKE YOURSELF THE ADMIN (change the email!) =====================
-- This lets you (and only you) read the help & prayer messages in the app: My profile → Help messages.
insert into public.app_admins (user_id) select id from auth.users where lower(email) = lower('YOUR-EMAIL-HERE') on conflict do nothing;
-- Check it worked: this should show 1 (or more).
select count(*) as admins_found from public.app_admins;
""")
open(os.path.join(R, 'supabase', 'activate-all.sql'), 'w', encoding='utf-8').write('\n'.join(out))
print('activate-all.sql written')
